"""Writing the generated Godot project to disk (everything except the scenes, which Godot writes)."""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

from .manifest import ADDON_DIR

AUTOLOADS = {
    "GameState": "res://addons/spawn_point/runtime/game_state.gd",
    "World": "res://addons/spawn_point/runtime/world.gd",
    "FX": "res://addons/spawn_point/runtime/fx.gd",
    "Sfx": "res://addons/spawn_point/runtime/sfx.gd",
}
LAYER_NAMES = ["world", "player", "enemy", "player_hurtbox", "enemy_hurtbox", "pickup"]
GENERATED_DIRS = ("entities", "levels", "rules", "sprites")


def slugify(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s or "game"


def _color(hex_color: str) -> str:
    h = hex_color.lstrip("#")
    r, g, b = (int(h[i : i + 2], 16) / 255 for i in (0, 2, 4))
    return f"Color({r:.4f}, {g:.4f}, {b:.4f}, 1)"


def project_godot(plan: dict, godot_feature: str = "4.6") -> str:
    vw, vh = plan["viewport"]
    lines = [
        "; Generated by Spawn Point. Safe to edit; rebuilding rewrites this file.",
        "config_version=5",
        "",
        "[application]",
        "",
        f"config/name={json.dumps(plan['name'])}",
        'run/main_scene="res://levels/main.tscn"',
        f'config/features=PackedStringArray("{godot_feature}")',
        "",
        "[autoload]",
        "",
        *[f'{k}="*{v}"' for k, v in AUTOLOADS.items()],
        "",
        "[display]",
        "",
        f"window/size/viewport_width={vw}",
        f"window/size/viewport_height={vh}",
        'window/stretch/mode="canvas_items"',
        'window/stretch/aspect="expand"',
        "",
        "[layer_names]",
        "",
        *[f'2d_physics/layer_{i + 1}="{n}"' for i, n in enumerate(LAYER_NAMES)],
        "",
        "[physics]",
        "",
        f"2d/default_gravity={float(plan['gravity'])}",
        "",
        "[rendering]",
        "",
        'renderer/rendering_method="gl_compatibility"',
        'renderer/rendering_method.mobile="gl_compatibility"',
        f"environment/defaults/default_clear_color={_color(plan['background'])}",
        "textures/canvas_textures/default_texture_filter=0",  # nearest: crisp pixel art
        "",
    ]
    return "\n".join(lines)


def write(out: Path, graph_data: dict, plan: dict, rules_source: str, godot_feature: str = "4.6",
          sprites: dict | None = None) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for d in GENERATED_DIRS:
        shutil.rmtree(out / d, ignore_errors=True)
        (out / d).mkdir()
    shutil.copytree(ADDON_DIR, out / "addons" / "spawn_point", dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns("*.import", "*.uid", "__pycache__"))
    (out / "project.godot").write_text(project_godot(plan, godot_feature))
    (out / "build_plan.json").write_text(json.dumps(plan, indent=1))
    (out / "rules" / "main_rules.gd").write_text(rules_source)
    for entity, sprite in (sprites or {}).items():
        sprite.sheet.save(out / "sprites" / f"{entity}.png")
    (out / "spawnpoint.json").write_text(json.dumps(graph_data, indent=2, ensure_ascii=False) + "\n")
    gi = out / ".gitignore"
    if not gi.exists():
        gi.write_text(".godot/\n")
