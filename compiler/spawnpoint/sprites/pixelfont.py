_G[" "] = ["...", "...", "...", "...", "...", "...", "..."]
SIZE = 9  # glyph box height (7 above the baseline, 2 below)
LINE = 11
INK, EDGE = (255, 255, 255, 255), (29, 26, 51, 255)


def _glyph(ch: str) -> np.ndarray:
    rows = _G[ch]
    w = max(len(r) for r in rows)
    a = np.zeros((SIZE, w), bool)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            a[y, x] = c == "#"
    return a


def font_files(name: str = "pixel", outline: bool = True) -> dict:
    """The atlas (glyphs with a 1 px outline, or plain ones) and the BMFont description that points at it."""
    glyphs = {ch: _glyph(ch) for ch in _G}
    cols = 16
    cell_w = max(g.shape[1] for g in glyphs.values()) + 2
    cell_h = SIZE + 2
    chars = sorted(glyphs, key=ord)
    rows = (len(chars) + cols - 1) // cols
    atlas = np.zeros((rows * cell_h, cols * cell_w, 4), np.uint8)
    lines = []
    for i, ch in enumerate(chars):
        g = glyphs[ch]
        h, w = g.shape
        ox, oy = (i % cols) * cell_w, (i // cols) * cell_h
        m = np.zeros((h + 2, w + 2), bool)
        m[1:-1, 1:-1] = g
        p = np.pad(m, 1)
        ring = (p[:-2, 1:-1] | p[2:, 1:-1] | p[1:-1, :-2] | p[1:-1, 2:] | p[:-2, :-2] | p[2:, 2:] | p[:-2, 2:] | p[2:, :-2]) & ~m
        tile = atlas[oy:oy + h + 2, ox:ox + w + 2]
        if outline:
            tile[ring] = EDGE
        tile[m] = INK
        if ch == " ":
            tile[...] = 0
        lines.append(f"char id={ord(ch)} x={ox} y={oy} width={w + 2} height={h + 2} xoffset=-1 yoffset=-1 "
                     f"xadvance={w + 1} page=0 chnl=15")
    head = [f'info face="{name}" size={SIZE} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 '
            "padding=0,0,0,0 spacing=0,0 outline=1",
            f"common lineHeight={LINE} base=7 scaleW={atlas.shape[1]} scaleH={atlas.shape[0]} pages=1 packed=0",
            f'page id=0 file="{name}.png"', f"chars count={len(chars)}"]
    return {f"{name}.fnt": "\n".join(head + lines) + "\n", f"{name}.png": atlas}
