"""Declarative rules -> generated GDScript (`rules.gd`).

A rule is {"on": <event>, "if": <expr>?, "do": [<action>...]}. Every reference is checked against
the graph and the component manifest, so the generated script is valid by construction.
"""

from __future__ import annotations

import ast
from dataclasses import dataclass

from .diagnostics import Diagnostics, did_you_mean, join_path
from .expr import ExprError, Scope, _attr_chain, entity_literal, gd_string, normalize, translate
from .graph import Rule
from .manifest import Manifest

GAMESTATE_EVENTS: dict[str, list[str]] = {
    "score_changed": ["score"],
    "lives_changed": ["lives"],
    "var_changed": ["name", "value"],
    "game_won": [],
    "game_lost": [],
}

# name -> (min args, max args, description)
BUILTINS: dict[str, tuple[int, int, str]] = {
    "add_score": (1, 1, "add_score(n)"),
    "set_var": (2, 2, 'set_var("name", value)'),
    "add_var": (2, 2, 'add_var("name", delta)'),
    "win": (0, 0, "win()"),
    "lose": (0, 0, "lose()"),
    "restart": (0, 0, "restart()"),
    "spawn": (1, 1, 'spawn("Entity") at the emitting entity'),
    "spawn_at": (3, 3, 'spawn_at("Entity", tile_x, tile_y)'),
    "destroy": (1, 1, 'destroy(self) | destroy("Entity") | destroy(event.arg)'),
    "shake": (1, 1, "shake(0..1)"),
    "freeze": (1, 1, "freeze(seconds)"),
    "sound": (1, 1, 'sound("name")'),
    "message": (1, 1, 'message("text")'),
}

HEADER = """\
# Generated by Spawn Point from the game graph (spawnpoint.json).
# Do not edit by hand: change the graph's "rules" and rebuild.
extends Node"""


@dataclass
class Event:
    kind: str  # "entity" | "gamestate" | "ready"
    label: str
    args: list[str]
    entity: str | None = None
    component: str | None = None
    signal: str | None = None


@dataclass
class RulesResult:
    source: str
    calls_win: bool


def resolve_event(on: str, entities: dict[str, list[str]], manifest: Manifest) -> Event:
    parts = on.strip().split(".")
    if parts == ["Game", "ready"]:
        return Event("ready", on, [])
    if parts[0] == "GameState":
        if len(parts) != 2 or parts[1] not in GAMESTATE_EVENTS:
            raise ExprError(f"unknown GameState event '{on}'",
                            did_you_mean(parts[-1], GAMESTATE_EVENTS))
        return Event("gamestate", on, GAMESTATE_EVENTS[parts[1]], signal=parts[1])
    ent = parts[0]
    if ent not in entities:
        raise ExprError(f"unknown entity '{ent}' in event '{on}'",
                        did_you_mean(ent, [*entities, "GameState", "Game"]))
    comps = entities[ent]
    if len(parts) == 3:
        comp_name, sig = parts[1], parts[2]
        if comp_name not in comps:
            raise ExprError(f"{ent} has no component '{comp_name}'", did_you_mean(comp_name, comps))
        comp = manifest.get(comp_name)
        if comp is None or sig not in comp.signals:
            raise ExprError(f"{comp_name} has no signal '{sig}'", did_you_mean(sig, comp.signals if comp else []))
    elif len(parts) == 2:
        sig = parts[1]
        owners = [c for c in comps if (m := manifest.get(c)) and sig in m.signals]
        if not owners:
            available = [f"{ent}.{s}" for c in comps if (m := manifest.get(c)) for s in m.signals]
            raise ExprError(f"no component of {ent} emits '{sig}'",
                            did_you_mean(f"{ent}.{sig}", available) if available else f"{ent} has no signals")
        if len(owners) > 1:
            raise ExprError(f"'{on}' is ambiguous", "Use one of: " + ", ".join(f"{ent}.{o}.{sig}" for o in owners))
        comp_name = owners[0]
    else:
        raise ExprError(f"cannot parse event '{on}'", "Use Entity.signal, Entity.Component.signal, GameState.<event> or Game.ready")
    sig_def = manifest.get(comp_name).signals[sig]
    return Event("entity", on, [a.name for a in sig_def.args], ent, comp_name, sig)


class _Actions:
    """Translates action calls of one rule into GDScript statements."""

    def __init__(self, scope: Scope, entities: dict[str, list[str]], manifest: Manifest):
        self.scope = scope
        self.entities = entities
        self.manifest = manifest
        self.calls_win = False

    def expr(self, node: ast.AST) -> str:
        return translate(ast.unparse(node), self.scope)

    def translate(self, src: str) -> str:
        try:
            node = ast.parse(normalize(src).strip(), mode="eval").body
        except SyntaxError as e:
            raise ExprError(f"syntax error in action '{src}': {e.msg}") from e
        if not isinstance(node, ast.Call):
            raise ExprError(f"action '{src}' must be a call like win() or Door.open()")
        if node.keywords:
            raise ExprError("keyword arguments are not supported in actions")
        if isinstance(node.func, ast.Name):
            return self.builtin(node.func.id, node.args)
        chain = _attr_chain(node.func)
        if chain is None:
            raise ExprError(f"cannot call '{ast.unparse(node.func)}'")
        return self.method_call(chain, node.args, src)

    def builtin(self, name: str, args: list[ast.expr]) -> str:
        if name not in BUILTINS:
            raise ExprError(f"unknown action '{name}()'", did_you_mean(name, BUILTINS))
        lo, hi, usage = BUILTINS[name]
        if not lo <= len(args) <= hi:
            raise ExprError(f"wrong number of arguments for {name}()", f"Usage: {usage}")
        e = self.expr
        match name:
            case "add_score":
                return f"GameState.add_score(int({e(args[0])}))"
            case "set_var" | "add_var":
                key = _string_literal(args[0], f"{name}() needs the variable name in quotes")
                return f"GameState.{name}({gd_string(key)}, {e(args[1])})"
            case "win":
                self.calls_win = True
                return "GameState.win()"
            case "lose":
                return "GameState.lose()"
            case "restart":
                return "GameState.restart.call_deferred()"
            case "spawn":
                ent = entity_literal(args[0], self.entities)
                if self.scope.self_entity is None:
                    raise ExprError("spawn() places the entity at the emitting entity, but this event has none",
                                    f'Use spawn_at("{ent}", tile_x, tile_y)')
                self.scope.used.add("source")
                return f'World.spawn.call_deferred({gd_string(ent)}, source.global_position)'
            case "spawn_at":
                ent = entity_literal(args[0], self.entities)
                return f"World.spawn_at_tile.call_deferred({gd_string(ent)}, int({e(args[1])}), int({e(args[2])}))"
            case "destroy":
                a = args[0]
                if isinstance(a, ast.Name) and a.id == "self":
                    return f"World.destroy({e(a)})"
                if isinstance(a, ast.Attribute):
                    return f"World.destroy({e(a)})"
                ent = entity_literal(a, self.entities)
                return f'World.destroy_all(&"{ent}")'
            case "shake":
                return f"FX.shake({e(args[0])})"
            case "freeze":
                return f"FX.hitstop({e(args[0])})"
            case "sound":
                snd = _string_literal(args[0], 'sound() needs a sound name in quotes, e.g. sound("coin")')
                return f"Sfx.play({gd_string(snd)})"
            case "message":
                return f"GameState.message(str({e(args[0])}))"
        raise AssertionError(name)

    def method_call(self, chain: list[str], args: list[ast.expr], src: str) -> str:
        head = chain[0]
        if head == "event":
            if len(chain) < 3:
                raise ExprError(f"cannot call '{'.'.join(chain)}'", "Use event.<arg>.<Component>.<method>()")
            target_code = self.expr(ast.parse(f"event.{chain[1]}", mode="eval").body)
            rest = chain[2:]
            ent_type = None
        elif head == "self":
            if self.scope.self_entity is None:
                raise ExprError("'self' is not available for this event (no emitting entity)")
            self.scope.used.add("source")
            target_code = "source"
            rest = chain[1:]
            ent_type = self.scope.self_entity
        elif head in self.entities:
            target_code = None
            rest = chain[1:]
            ent_type = head
        else:
            raise ExprError(f"unknown call target '{head}' in '{src}'",
                            did_you_mean(head, [*self.entities, "self", "event"]))

        if len(rest) == 2:
            comp_name, method = rest
        elif len(rest) == 1:
            method = rest[0]
            comp_name = self._component_for(method, ent_type)
        else:
            raise ExprError(f"cannot call '{'.'.join(chain)}'", "Use Entity.method() or Entity.Component.method()")

        comp = self.manifest.get(comp_name)
        if comp is None:
            raise ExprError(f"unknown component '{comp_name}'", did_you_mean(comp_name, self.manifest.components))
        if ent_type is not None and comp_name not in self.entities[ent_type]:
            raise ExprError(f"{ent_type} has no component '{comp_name}'", did_you_mean(comp_name, self.entities[ent_type]))
        m = comp.methods.get(method)
        if m is None:
            raise ExprError(f"{comp_name} has no method '{method}'", did_you_mean(method, comp.methods))
        if not m.min_args <= len(args) <= len(m.args):
            sig = ", ".join(a.name for a in m.args)
            raise ExprError(f"{comp_name}.{method}() takes {m.min_args}-{len(m.args)} argument(s), got {len(args)}",
                            f"Signature: {method}({sig})")
        arg_code = "[" + ", ".join(self.expr(a) for a in args) + "]"
        if target_code is None:
            return f'World.call_all(&"{ent_type}", &"{comp_name}", &"{method}", {arg_code})'
        return f'World.call_on({target_code}, &"{comp_name}", &"{method}", {arg_code})'

    def _component_for(self, method: str, ent_type: str | None) -> str:
        candidates = self.entities[ent_type] if ent_type else list(self.manifest.components)
        owners = [c for c in candidates if (m := self.manifest.get(c)) and method in m.methods]
        if not owners:
            available = sorted({mm for c in candidates if (m := self.manifest.get(c)) for mm in m.methods})
            where = ent_type or "any component"
            raise ExprError(f"{where} has no method '{method}'", did_you_mean(method, available))
        if len(owners) > 1:
            raise ExprError(f"method '{method}' is ambiguous", "Name the component: " + ", ".join(f"{o}.{method}()" for o in owners))
        return owners[0]


def _string_literal(node: ast.AST, message: str) -> str:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    raise ExprError(message)


def compile_rules(rules: list[Rule], entities: dict[str, list[str]], manifest: Manifest,
                  diags: Diagnostics) -> RulesResult:
    binds: list[str] = []
    ready_calls: list[str] = []
    funcs: list[str] = []
    calls_win = False
    for i, rule in enumerate(rules):
        path = join_path("rules", i)
        try:
            ev = resolve_event(rule.on, entities, manifest)
        except ExprError as e:
            diags.error("E_RULE_EVENT", path + ".on", str(e), e.hint)
            continue
        arg_names = {a: f"a_{a}" for a in ev.args}
        scope = Scope(manifest, entities, arg_names, ev.entity if ev.kind == "entity" else None)
        ok = True
        cond = None
        if rule.if_:
            try:
                cond = translate(rule.if_, scope)
            except ExprError as e:
                diags.error("E_RULE_IF", path + ".if", str(e), e.hint)
                ok = False
        actions = _Actions(scope, entities, manifest)
        body: list[str] = []
        if not rule.actions:
            diags.error("E_RULE_DO", path + ".do", "rule has no actions")
            ok = False
        for j, act in enumerate(rule.actions):
            try:
                body.append(actions.translate(act))
            except ExprError as e:
                diags.error("E_RULE_DO", join_path(path, "do", j), str(e), e.hint)
                ok = False
        if not ok:
            continue
        calls_win |= actions.calls_win

        fname = f"_rule_{i}"
        params = [(gd if gd in scope.used else "_" + gd) for gd in arg_names.values()]
        if ev.kind == "entity":
            params.append("source" if "source" in scope.used else "_source")
            binds.append(f'World.bind_signal(&"{ev.entity}", &"{ev.component}", &"{ev.signal}", {fname})')
        elif ev.kind == "gamestate":
            binds.append(f"GameState.{ev.signal}.connect({fname})")
        else:
            ready_calls.append(f"{fname}()")

        comment = f"# Rule {i}: on {rule.on}" + (f" if {rule.if_}" if rule.if_ else "")
        lines = [comment, f"func {fname}({', '.join(params)}) -> void:"]
        if cond:
            lines += [f"\tif not {cond}:", "\t\treturn"]
        lines += [f"\t{stmt}" for stmt in body]
        funcs.append("\n".join(lines))

    ready = ["func _ready() -> void:"]
    ready += [f"\t{b}" for b in binds]
    if ready_calls:
        ready.append("\t_on_game_ready.call_deferred()")
    if len(ready) == 1:
        ready.append("\tpass")
    chunks = [HEADER, "\n".join(ready)]
    if ready_calls:
        chunks.append("\n".join(["func _on_game_ready() -> void:", *[f"\t{c}" for c in ready_calls]]))
    chunks += funcs
    return RulesResult("\n\n\n".join(chunks) + "\n", calls_win)
